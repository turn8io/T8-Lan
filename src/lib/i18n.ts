const DICTS: Record<Lang, Record<TKey, string>> = { nl, en, de, fr, it, es };

/** Systeemtaal van Windows (WebView2 geeft de weergavetaal door), of Engels. */
export function systemLang(): Lang {
  const tag = (navigator.language || "en").toLowerCase();
  const primary = tag.split(/[-_]/)[0];
  return (primary in DICTS ? primary : "en") as Lang;
}

/** De effectieve taal voor een instelling ("auto" = systeemtaal). */
export function resolveLang(setting: LangSetting | undefined | null): Lang {
  if (!setting || setting === "auto") return systemLang();
  return setting in DICTS ? setting : "en";
}

let current: Lang = systemLang();

/** Stel de actieve taal in; App remount daarna de shell zodat alle teksten verversen. */
export function setLanguage(lang: Lang) {
  current = lang;
}

export function currentLang(): Lang {
  return current;
}

export function t(key: TKey): string {
  return DICTS[current][key] ?? en[key] ?? key;
}
